"""Build base cards from chapter headwords + MIT ECDICT; never reuse book meanings."""
import csv, json, re, hashlib
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'private' / 'sources'
OUT = ROOT / 'public' / 'data'
OUT.mkdir(exist_ok=True)
refs = list(csv.DictReader((SRC / 'chapter-headwords-reference.csv').open(encoding='utf-8-sig')))
entries = {}
for row in refs:
    word = row['word'].strip()
    key = word.lower()
    chapter = int(row['sort'])
    if not 1 <= chapter <= 22: raise ValueError(chapter)
    entry = entries.setdefault(key, {'word':word, 'chapters':[]})
    if chapter not in entry['chapters']: entry['chapters'].append(chapter)
dictionary = {}
with (SRC / 'ecdict.csv').open(encoding='utf-8-sig', newline='') as f:
    for row in csv.DictReader(f):
        key = row['word'].lower()
        if key in entries: dictionary[key] = row
labels = {'p':'过去式','d':'过去分词','i':'现在分词','3':'第三人称单数','r':'比较级','t':'最高级','s':'复数','0':'原形'}
cards = []
for key, info in entries.items():
    row = dictionary.get(key)
    if not row:
        if key != 'shade-tolerant': raise ValueError('Missing dictionary entry: '+key)
        meaning='adj. 耐阴的；能够在较弱光照下生长的'
        ipa=''
        extra=[['构词提示','shade（阴凉处）＋ tolerant（能耐受的）→ shade-tolerant（耐阴的）。']]
        source='词间独立编写'
    else:
        raw=row['translation'].replace('\\n','\n').strip()
        lines=[line.strip() for line in raw.splitlines() if line.strip()]
        common=[line for line in lines if not line.startswith('[')]
        meaning='；'.join(common or lines)
        ipa=row['phonetic'].strip()
        if ipa: ipa='/'+ipa.strip('/')+'/'
        extra=[]
        forms=[]
        for item in row['exchange'].split('/'):
            if ':' not in item: continue
            typ, value=item.split(':',1)
            if typ in labels and value: forms.append(labels[typ]+'：'+value)
        if forms: extra.append(['词形变化','；'.join(forms)])
        if len(common)!=len(lines): extra.append(['词典其他义项','；'.join(x for x in lines if x.startswith('['))])
        source='ECDICT · MIT License（词典释义及词形，未逐条完成语境校订）'
    if not meaning: raise ValueError('Empty meaning: '+key)
    cards.append({'id':'word:'+key,'word':info['word'],'chapters':info['chapters'],'ipa':ipa,'pos':'词典释义','meaning':meaning,'collocation':'','tokens':[],'translation':'','extra':extra,'source':source})
(OUT/'wordbook.js').write_text('// Generated by scripts/build-wordbook.py. Dictionary data: ECDICT (MIT).\nexport const baseWords='+json.dumps(cards,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
with (OUT/'chapter-headwords.csv').open('w',encoding='utf-8-sig',newline='') as f:
    writer=csv.writer(f);writer.writerow(['word','chapter'])
    for card in cards:
        for chapter in card['chapters']: writer.writerow([card['word'],chapter])
(OUT/'ECDICT-LICENSE.txt').write_bytes((SRC/'ECDICT-LICENSE.txt').read_bytes())
manifest={'generated':'2026-11-10','referenceRows':len(refs),'uniqueHeadwords':len(cards),'dictionaryMatches':len(dictionary),'independentDefinitions':1,'chapters':22,'sources':{'headwordChapterReference':'https://github.com/LynnShaw/vocabulary_for_ielts/blob/main/word_list.csv','dictionary':'https://github.com/skywind3000/ECDICT'},'sha256':{p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in [SRC/'chapter-headwords-reference.csv',SRC/'ecdict.csv']},'note':'仅提取参考表词目及章节编号；释义、音标、词形取自 ECDICT，不复制参考表中文释义。章节与纸质版本未逐项核验，不是官方授权电子书。例句及逐词解释覆盖情况见站内统计。'}
(OUT/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf-8')
print(json.dumps({k:manifest[k] for k in ['referenceRows','uniqueHeadwords','dictionaryMatches']},ensure_ascii=True))
